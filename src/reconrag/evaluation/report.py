"""Write result tables to ``results/`` (CSV, one file per table) and a readable ``results/summary.md``."""

from __future__ import annotations

import csv
import datetime as dt
import platform

from . import RESULTS

TITLES = {
    "amendments": "Tier 1 - Amendments (implicit setting, test split, official gold labels)",
    "replacements": "Tier 1 - Full replacements (test split, macro-F1 against four silver references)",
    "verification": "Tier 1 - Human verification of the three-model consensus on full replacements (one author, 50 provisions)",
    "retrieval": "Tier 2 - Retrieval (test split, k=5, share of questions; no LLM involved)",
    "answers": "Tier 2 - Answers (test split, LLM judge; stale = share of current-rule questions)",
    "significance": "Tier 2 - Exact McNemar tests, ReconRAG vs. prompt-based baselines (Holm-corrected)",
    "judge": "Answer graders vs. human rater (53 stratified answers)",
}


KEYS = {"amendments": ["method"], "replacements": ["reference"], "verification": ["status"], "retrieval": ["backend", "condition"],
        "answers": ["generator", "condition"], "significance": ["generator", "metric", "baseline"], "judge": ["grader"]}


def write_csv(name: str, rows: list[dict]) -> None:
    RESULTS.mkdir(parents=True, exist_ok=True)
    with open(RESULTS / f"{name}.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def compare(name: str, rows: list[dict]) -> list[str]:
    """Differences between freshly computed rows and results/<name>.csv.

    Rows are matched on their text columns (e.g. backend + condition); reference rows that were not recomputed
    (such as Dense retrieval when --dense is not given) are ignored.
    """
    path = RESULTS / f"{name}.csv"
    if not path.exists():
        return [f"{name}.csv: no reference file"]
    ref = list(csv.DictReader(open(path, encoding="utf-8")))
    keycols = KEYS[name]
    index = {tuple(r[c] for c in keycols): r for r in ref}
    out = []
    for r in rows:
        k = tuple(r[c] for c in keycols)
        if k not in index:
            out.append(f"{name}.csv: row {k} missing in reference")
            continue
        for c, v in r.items():
            if str(v) != index[k].get(c):
                out.append(f"{name}.csv {k} {c}: reference {index[k].get(c)}, now {v}")
    return out


def _fmt(v) -> str:
    return f"{v:.3f}" if isinstance(v, float) else str(v)


def markdown_table(rows: list[dict]) -> str:
    cols = list(rows[0])
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(_fmt(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(lines)


def console_table(rows: list[dict]) -> str:
    cols = list(rows[0])
    width = {c: max(len(c), *(len(_fmt(r[c])) for r in rows)) for c in cols}
    line = lambda vals: "  ".join(str(v).ljust(width[c]) for c, v in zip(cols, vals))
    return "\n".join([line(cols), line("-" * width[c] for c in cols)] + [line(_fmt(r[c]) for c in cols) for r in rows])


def write_summary(tables: dict[str, list[dict]], figures: list[str], seconds: float, dense: bool) -> None:
    parts = ["# ReconRAG results", "",
             f"Generated by `python main.py{' --dense' if dense else ''}` on {dt.date.today().isoformat()} "
             f"(Python {platform.python_version()}, {seconds:.0f} s). Each table is also saved as CSV in this folder.", ""]
    for name, rows in tables.items():
        parts += [f"## {TITLES[name]}", "", f"File: `{name}.csv`", "", markdown_table(rows), ""]
    if figures:
        parts += ["## Figures", ""] + [f"- `figures/{f}`" for f in figures] + [""]
    (RESULTS / "summary.md").write_text("\n".join(parts), encoding="utf-8")
